"""动态模块命名、源码导入和缓存回滚；不注册事件处理器或启动任务。"""

from __future__ import annotations

import hashlib
import importlib
import importlib.util
import re
import sys
from pathlib import Path
from types import ModuleType

USER_PACKAGE = "fllbot_user_plugins"
BUILTIN_PACKAGE = "fllbot.builtin_plugins"
_SAFE_NAME = re.compile(r"[^0-9A-Za-z_]")


def module_name_for(path: Path, builtin: bool) -> str:
    stem = path.name if path.is_dir() else path.stem
    safe = _SAFE_NAME.sub("_", stem)
    digest = hashlib.sha256(str(path.resolve()).encode()).hexdigest()[:16]
    return f"{BUILTIN_PACKAGE}.{safe}" if builtin else f"{USER_PACKAGE}.{safe}_{digest}"


def import_plugin(path: Path, module_name: str, *, builtin: bool) -> ModuleType:
    # 导入前备份同名模块及其子模块：新源码导入失败时恢复，
    # 保证正在运行的旧插件仍能继续做惰性导入。
    backup = {
        key: value
        for key, value in list(sys.modules.items())
        if key == module_name or key.startswith(module_name + ".")
    }
    try:
        # 直接编译源码执行：避免 __pycache__ 里同秒内写入的旧字节码被复用。
        purge_modules(module_name)
        if builtin:
            importlib.import_module(BUILTIN_PACKAGE)
        else:
            ensure_parent_package()
        if path.is_dir():
            for cached in path.rglob("__pycache__/*.pyc"):
                # Only generated bytecode physically inside this plugin package is removed.
                if cached.resolve().is_relative_to(path.resolve()):
                    cached.unlink(missing_ok=True)
        importlib.invalidate_caches()
        is_package = path.is_dir()
        location = (path / "__init__.py") if is_package else path
        source = location.read_text(encoding="utf-8")

        module = ModuleType(module_name)
        module.__spec__ = importlib.util.spec_from_file_location(
            module_name,
            location,
            submodule_search_locations=[str(path)] if is_package else None,
        )
        module.__loader__ = module.__spec__.loader if module.__spec__ else None
        module.__file__ = str(location)
        module.__package__ = module_name if is_package else module_name.rpartition(".")[0]
        if is_package:
            module.__path__ = [str(path)]  # type: ignore[attr-defined]
        sys.modules[module_name] = module
        try:
            code = compile(source, str(location), "exec")
            exec(code, module.__dict__)  # noqa: S102 - 插件源码来自本地可信目录
        except Exception:
            sys.modules.pop(module_name, None)
            raise
        return module
    except Exception:
        purge_modules(module_name)
        sys.modules.update(backup)
        raise


def purge_modules(module_name: str) -> None:
    for key in [key for key in sys.modules if key == module_name or key.startswith(module_name + ".")]:
        sys.modules.pop(key, None)


def ensure_parent_package() -> None:
    if USER_PACKAGE in sys.modules:
        return
    package = ModuleType(USER_PACKAGE)
    package.__path__ = []  # type: ignore[attr-defined]
    sys.modules[USER_PACKAGE] = package
